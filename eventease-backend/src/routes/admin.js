import { Router } from 'express';
import { auth } from '../middleware/auth.js';
import { requireRole } from '../middleware/requireRole.js';
import { validate } from '../middleware/validate.js';
import { asyncHandler } from '../utils/asyncHandler.js';
import * as controller from '../controllers/adminController.js';
import { activityQuerySchema, adminEventsQuerySchema, adminRequestsQuerySchema, adminUsersQuerySchema, categoryParamsSchema, idOnlySchema, noInputSchema, rejectSchema, removeSchema, requestReviewSchema, userRoleSchema, userStatusSchema, bookingQuerySchema, reportsQuerySchema } from '../validators/schemas.js';
import { z } from 'zod';

const router = Router();
const id = z.coerce.number().int().positive();
const categoryBody = z.object({ body: z.object({ categoryName: z.string().trim().min(2).max(30) }) });
const categoryUpdate = z.object({ params: z.object({ id }), body: z.object({ categoryName: z.string().trim().min(2).max(30) }) });
router.use(auth, requireRole('admin'));
router.get('/dashboard', validate(noInputSchema), asyncHandler(controller.dashboard));
router.get('/events/pending', validate(noInputSchema), asyncHandler(controller.pendingEvents));
router.get('/events', validate(adminEventsQuerySchema), asyncHandler(controller.events));
router.patch('/events/:id/approve', validate(idOnlySchema), asyncHandler(controller.approveEvent));
router.patch('/events/:id/reject', validate(rejectSchema), asyncHandler(controller.rejectEvent));
router.patch('/events/:id/remove', validate(removeSchema), asyncHandler(controller.removeEvent));
router.get('/users', validate(adminUsersQuerySchema), asyncHandler(controller.users));
router.patch('/users/:id/status', validate(userStatusSchema), asyncHandler(controller.userStatus));
router.patch('/users/:id/role', validate(userRoleSchema), asyncHandler(controller.userRole));
router.delete('/users/:id', validate(idOnlySchema), asyncHandler(controller.deleteUser));
router.get('/organizer-requests', validate(adminRequestsQuerySchema), asyncHandler(controller.organizerRequests));
router.patch('/organizer-requests/:id/approve', validate(idOnlySchema), asyncHandler(controller.approveOrganizerRequest));
router.patch('/organizer-requests/:id/reject', validate(requestReviewSchema), asyncHandler(controller.rejectOrganizerRequest));
router.get('/bookings/export', validate(bookingQuerySchema), asyncHandler(controller.exportBookings));
router.get('/bookings', validate(bookingQuerySchema), asyncHandler(controller.bookings));
router.get('/categories', validate(noInputSchema), asyncHandler(controller.categories));
router.post('/categories', validate(categoryBody), asyncHandler(controller.createCategory));
router.put('/categories/:id', validate(categoryUpdate), asyncHandler(controller.updateCategory));
router.delete('/categories/:id', validate(categoryParamsSchema), asyncHandler(controller.deleteCategory));
router.get('/reports/export', validate(reportsQuerySchema), asyncHandler(controller.exportReports));
router.get('/reports', validate(reportsQuerySchema), asyncHandler(controller.reports));
router.get('/activity', validate(activityQuerySchema), asyncHandler(controller.activity));
export default router;
