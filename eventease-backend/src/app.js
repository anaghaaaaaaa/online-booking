import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import morgan from 'morgan';
import { env } from './config/env.js';
import { pool } from './config/db.js';
import { apiLimiter } from './middleware/rateLimit.js';
import { errorHandler, notFound } from './middleware/errorHandler.js';
import { asyncHandler } from './utils/asyncHandler.js';
import authRoutes from './routes/auth.js';
import eventRoutes from './routes/events.js';
import categoryRoutes from './routes/categories.js';
import bookingRoutes from './routes/bookings.js';
import userRoutes from './routes/users.js';
import organizerRoutes from './routes/organizer.js';
import adminRoutes from './routes/admin.js';
import notificationRoutes from './routes/notifications.js';
import contactRoutes from './routes/contact.js';
import organizerRequestRoutes from './routes/organizerRequests.js';

export const app = express();
app.disable('x-powered-by');
app.set('trust proxy', env.NODE_ENV === 'production' ? 1 : false);
app.use(helmet());
app.use(cors({ origin: env.CLIENT_ORIGIN, credentials: true }));
app.use(express.json({ limit: '100kb' }));
app.use(express.urlencoded({ extended: false, limit: '100kb' }));
app.use(cookieParser());
app.use(morgan(env.NODE_ENV === 'production' ? 'combined' : 'dev'));
app.use('/api/v1', apiLimiter);

app.get('/health', (request, response) => response.json({ success: true, data: { status: 'ok' } }));
app.get('/api/v1/health', asyncHandler(async (request, response) => {
  await pool.query('SELECT 1');
  response.json({ success: true, data: { status: 'ok', database: 'connected' } });
}));
app.use('/api/v1/auth', authRoutes);
app.use('/api/v1/events', eventRoutes);
app.use('/api/v1/categories', categoryRoutes);
app.use('/api/v1/bookings', bookingRoutes);
app.use('/api/v1', userRoutes);
app.use('/api/v1/organizer', organizerRoutes);
app.use('/api/v1/admin', adminRoutes);
app.use('/api/v1/notifications', notificationRoutes);
app.use('/api/v1/contact', contactRoutes);
app.use('/api/v1/organizer-requests', organizerRequestRoutes);
app.use(notFound);
app.use(errorHandler);
